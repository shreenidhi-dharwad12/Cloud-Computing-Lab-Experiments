"""
Generate results/RESULTS.md (observation tables + measured observations)
from results/workload_results.csv, results/runs.csv and results/run_info.json.

Flow:  benchmark.py -> CSV -> generate_graphs.py / generate_report.py

Every number in RESULTS.md is computed from the CSV files, so the report
always matches the graphs and the benchmark output of the same run.
"""

import csv
import json
import os
import sys

RESULTS_DIR = "results"
SERVICES = ["patient-service", "doctor-service", "appointment-service"]

# A doubling of concurrency that raises throughput by less than this is
# treated as "throughput has stopped scaling" (saturation).
SATURATION_GAIN_PCT = 10.0


def number(value):
    return float(value) if value not in ("", None) else float("nan")


def read_csv(name):
    path = os.path.join(RESULTS_DIR, name)
    if not os.path.exists(path):
        sys.exit(f"{path} not found - run  python benchmark.py  first.")
    with open(path, newline="") as file:
        return list(csv.DictReader(file))


def pct_change(old, new):
    return (new - old) / old * 100 if old else float("nan")


def main():
    rows = read_csv("workload_results.csv")
    runs = read_csv("runs.csv")
    with open(os.path.join(RESULTS_DIR, "run_info.json")) as file:
        info = json.load(file)

    idle = next(r for r in rows if r["Workload"] == "Idle")
    load = sorted((r for r in rows if r["Workload"] != "Idle"),
                  key=lambda r: int(r["Concurrency"]))
    first, last = load[0], load[-1]

    out = []
    w = out.append

    w("# Measured Results\n")
    w("_This file is generated by `generate_report.py` from the CSV files in "
      "`results/`. Do not edit the numbers by hand - re-run the benchmark instead._\n")

    w("## Test set-up\n")
    w(f"- **Date of run:** {info['timestamp']}")
    w(f"- **Endpoint under test:** `{info['target']}` "
      "(end-to-end: appointment-service -> patient-service + doctor-service)")
    w(f"- **Concurrency levels:** {', '.join(map(str, info['levels']))}")
    w(f"- **Each run:** at least {info['min_requests_per_run']} requests and at least "
      f"{info['min_duration_per_run_s']:.0f} s")
    w(f"- **Repetitions per level:** {info['repetitions']} (results below are the mean)")
    w(f"- **Warm-up:** {info['warmup_requests']} requests before measuring (discarded)")
    w(f"- **Load model:** {info['load_model']}")
    w(f"- **Throughput:** {info['throughput_definition']}")
    w(f"- **Machine:** {info['host_os']}, {info['host_cpu_count']} logical CPUs, "
      f"Docker {info['docker_server']}, Python {info['python']}")
    w("- **CPU %:** from `docker stats`, 100 % = one full CPU core. "
      "Sampled about once per second during each run.\n")

    # ---- main observation table (columns required by the lab manual) -------
    w("## Observation table\n")
    w("| Workload | Concurrency | Requests | Avg response time (ms) | p95 (ms) "
      "| Throughput (req/s) | Failed | CPU avg, all 3 services (%) "
      "| Memory avg, all 3 services (MiB) |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    w(f"| Idle | 0 | 0 | - | - | - | - | {number(idle['Total_CPU_avg_pct']):.2f} "
      f"| {number(idle['Total_MEM_avg_MiB']):.2f} |")
    for r in load:
        w(f"| {r['Workload']} | {r['Concurrency']} | {r['Requests_total']} "
          f"| {number(r['RT_avg_ms']):.2f} ± {number(r['RT_avg_std_ms']):.2f} "
          f"| {number(r['RT_p95_ms']):.2f} "
          f"| {number(r['Throughput_req_s']):.2f} ± {number(r['Throughput_std_req_s']):.2f} "
          f"| {r['Failed_total']} "
          f"| {number(r['Total_CPU_avg_pct']):.2f} | {number(r['Total_MEM_avg_MiB']):.2f} |")
    w("\n`±` = standard deviation across the repetitions. "
      "Requests = total over all repetitions.\n")

    # ---- per-service table --------------------------------------------------
    w("## Resource usage per microservice\n")
    w("| Workload | Conc. | " + " | ".join(
        f"{s.replace('-service', '')} CPU avg / peak (%)" for s in SERVICES) + " | "
      + " | ".join(f"{s.replace('-service', '')} Mem avg / peak (MiB)" for s in SERVICES) + " |")
    w("|---|---:|" + "---:|" * (2 * len(SERVICES)))
    for r in [idle] + load:
        cpu = " | ".join(
            f"{number(r[f'{s}_CPU_avg_pct']):.2f} / {number(r[f'{s}_CPU_peak_pct']):.2f}"
            for s in SERVICES)
        mem = " | ".join(
            f"{number(r[f'{s}_MEM_avg_MiB']):.2f} / {number(r[f'{s}_MEM_peak_MiB']):.2f}"
            for s in SERVICES)
        w(f"| {r['Workload']} | {r['Concurrency']} | {cpu} | {mem} |")
    w("")

    # ---- measured observations ---------------------------------------------
    w("## Observations (computed from the data)\n")

    rt1, rtn = number(first["RT_avg_ms"]), number(last["RT_avg_ms"])
    w(f"1. **Response time:** average response time went from **{rt1:.2f} ms** at "
      f"concurrency {first['Concurrency']} to **{rtn:.2f} ms** at concurrency "
      f"{last['Concurrency']} ({rtn / rt1:.1f}x). p95 went from "
      f"{number(first['RT_p95_ms']):.2f} ms to {number(last['RT_p95_ms']):.2f} ms.")

    thr = [number(r["Throughput_req_s"]) for r in load]
    best = max(range(len(load)), key=lambda i: thr[i])
    w(f"2. **Throughput:** went from **{thr[0]:.2f} req/s** at concurrency "
      f"{first['Concurrency']} to **{thr[-1]:.2f} req/s** at concurrency "
      f"{last['Concurrency']}. The highest value was {thr[best]:.2f} req/s at "
      f"concurrency {load[best]['Concurrency']}.")

    saturation = None
    for i in range(1, len(load)):
        gain = pct_change(thr[i - 1], thr[i])
        if gain < SATURATION_GAIN_PCT:
            saturation = i
            break
    if saturation is not None:
        prev, cur = load[saturation - 1], load[saturation]
        w(f"3. **Saturation:** going from concurrency {prev['Concurrency']} to "
          f"{cur['Concurrency']} changed throughput by only "
          f"{pct_change(thr[saturation - 1], thr[saturation]):+.1f} % while average "
          f"response time changed by "
          f"{pct_change(number(prev['RT_avg_ms']), number(cur['RT_avg_ms'])):+.1f} %. "
          f"Throughput levels off between concurrency {prev['Concurrency']} and "
          f"{cur['Concurrency']}: beyond that the application cannot complete "
          "requests any faster, so extra concurrent requests mostly wait in a "
          "queue, which shows up as higher response time.")
        if best < len(load) - 1 and pct_change(thr[best], thr[-1]) < -2:
            w(f"   After its peak at concurrency {load[best]['Concurrency']}, throughput "
              f"fell by {abs(pct_change(thr[best], thr[-1])):.1f} % at concurrency "
              f"{last['Concurrency']} - more threads competing for the same CPU adds "
              "context-switching overhead without adding capacity.")
    else:
        w("3. **Saturation:** throughput kept increasing by at least "
          f"{SATURATION_GAIN_PCT:.0f} % for every doubling of concurrency, so the "
          "application did not saturate within the tested levels.")

    # Little's law: in a closed loop, concurrency ~= throughput x response time
    products = [number(r["Throughput_req_s"]) * number(r["RT_avg_ms"]) / 1000 for r in load]
    deviations = [abs(p - int(r["Concurrency"])) / int(r["Concurrency"])
                  for p, r in zip(products, load)]
    if max(deviations) <= 0.2:
        verdict = ("Each product is within 20 % of the concurrency level, so the "
                   "measured response times and throughputs are consistent.")
    else:
        verdict = ("Some products differ from the concurrency level by more than "
                   "20 %; the gap is time the load generator spends between "
                   "requests (Python thread scheduling / the GIL on the client), "
                   "which is not part of the measured response time.")
    w("4. **Consistency check (Little's law, N = X x R):** "
      + "; ".join(
          f"c={r['Concurrency']}: {number(r['Throughput_req_s']):.1f} req/s x "
          f"{number(r['RT_avg_ms']) / 1000:.4f} s = {p:.2f}"
          for r, p in zip(load, products))
      + ". " + verdict)

    failed = sum(int(r["Failed_total"]) for r in load)
    total = sum(int(r["Requests_total"]) for r in load)
    failure_types = {}
    for run in runs:
        for item in filter(None, run["FailureTypes"].split(";")):
            key, value = item.split("=")
            failure_types[key] = failure_types.get(key, 0) + int(value)
    if failed:
        types = ", ".join(f"{k}: {v}" for k, v in failure_types.items())
        w(f"5. **Failures:** {failed} of {total} requests failed "
          f"({failed / total * 100:.2f} %). Failure types: {types}.")
    else:
        w(f"5. **Failures:** all {total} measured requests succeeded (0 failed).")

    def top_service(row, metric, unit):
        values = {s: number(row[f"{s}_{metric}_avg_{unit}"]) for s in SERVICES}
        name = max(values, key=values.get)
        return name, values

    cpu_name, cpu_values = top_service(last, "CPU", "pct")
    others = [v for s, v in cpu_values.items() if s != cpu_name]
    ratio = cpu_values[cpu_name] / (sum(others) / len(others)) if sum(others) else float("nan")
    w(f"6. **Highest CPU user:** at concurrency {last['Concurrency']}, "
      f"**{cpu_name}** used the most CPU: "
      + ", ".join(f"{s} {v:.2f} %" for s, v in cpu_values.items())
      + f" ({ratio:.1f}x the average of the other two).")

    mem_name, mem_values = top_service(last, "MEM", "MiB")
    growth = {s: mem_values[s] - number(idle[f"{s}_MEM_avg_MiB"]) for s in SERVICES}
    grow_name = max(growth, key=growth.get)
    w(f"7. **Memory:** at concurrency {last['Concurrency']}, **{mem_name}** had the "
      "highest memory: "
      + ", ".join(f"{s} {v:.2f} MiB" for s, v in mem_values.items()) + ". "
      "Most of this is each container's starting footprint, already present when "
      "idle. The part caused by the load is the increase from idle: "
      + ", ".join(f"{s} {g:+.2f} MiB" for s, g in growth.items())
      + f", so **{grow_name}** had the largest load-related memory increase.")

    idle_cpu, load_cpu = number(idle["Total_CPU_avg_pct"]), number(last["Total_CPU_avg_pct"])
    idle_mem, load_mem = number(idle["Total_MEM_avg_MiB"]), number(last["Total_MEM_avg_MiB"])
    w(f"8. **Load vs idle:** total CPU of the three containers rose from "
      f"{idle_cpu:.2f} % when idle to {load_cpu:.2f} % at concurrency "
      f"{last['Concurrency']}. Total memory changed from {idle_mem:.2f} MiB to "
      f"{load_mem:.2f} MiB ({load_mem - idle_mem:+.2f} MiB).")

    w("\n## Graphs\n")
    for file, title in (
        ("01-response-time.png", "Concurrency vs Response Time"),
        ("02-throughput.png", "Concurrency vs Throughput"),
        ("03-cpu-utilization.png", "Concurrency vs CPU Utilization (per service)"),
        ("04-memory-utilization.png", "Concurrency vs Memory Usage (per service)"),
        ("05-resource-by-service.png", "Resource usage per microservice at highest load"),
    ):
        w(f"### {title}\n\n![{title}](../graphs/{file})\n")

    path = os.path.join(RESULTS_DIR, "RESULTS.md")
    with open(path, "w", encoding="utf-8") as file:
        file.write("\n".join(out) + "\n")
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
